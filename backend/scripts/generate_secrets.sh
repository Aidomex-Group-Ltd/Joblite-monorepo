#!/usr/bin/env bash
# Generate the local development secrets with openssl.
#
# Secret values never live in tracked source. They are written to gitignored
# files that both repositories read at configuration time:
#
#   backend/secrets/dev.env    DATABASE_URL, JWT_SECRET
#   frontend/secrets/dev.env   SECRET_KEY_BASE, LIVE_SIGNING_SALT
#
# The files hold plain KEY=VALUE lines, so a shell can consume them with
# `set -a; . backend/secrets/dev.env`. backend/config/secrets.exs loads the
# same files into the Mix configuration for the :dev environment.
#
# The script is idempotent: an existing value is kept unless --force is given.
#
# Usage:
#   scripts/generate_secrets.sh           # keep existing values, add missing ones
#   scripts/generate_secrets.sh --force   # regenerate every value
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BACKEND_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
WORKSPACE_DIR="$(cd "${BACKEND_DIR}/.." && pwd)"
FRONTEND_DIR="${WORKSPACE_DIR}/frontend"

BACKEND_SECRETS="${BACKEND_DIR}/secrets/dev.env"
FRONTEND_SECRETS="${FRONTEND_DIR}/secrets/dev.env"

FORCE=0
case "${1:-}" in
  "") ;;
  --force) FORCE=1 ;;
  *)
    echo "usage: $0 [--force]" >&2
    exit 2
    ;;
esac

command -v openssl >/dev/null 2>&1 || {
  echo "error: openssl is required to generate secrets" >&2
  exit 1
}

# The development database is the compose.yaml PostgreSQL instance bound to
# 127.0.0.1:5543. These credentials are the documented local-only defaults.
DATABASE_URL="ecto://joblite:joblite_local_only@localhost:5543/joblite_dev_db"

read_value() {
  # $1 = file, $2 = key. Prints the stored value, if any.
  [ -f "$1" ] || return 0
  sed -n "s/^${2}=//p" "$1" | head -n 1
}

secret_value() {
  # $1 = file, $2 = key, $3 = random bytes of entropy. Prints the stored
  # value, or a fresh one when it is missing or --force asked for a new one.
  local existing
  existing="$(read_value "$1" "$2")"
  if [ -n "$existing" ] && [ "$FORCE" -eq 0 ]; then
    printf '%s' "$existing"
  else
    openssl rand -hex "$3"
  fi
}

ensure_env_file() {
  # $1 = file, $2 = header description. Creates the file with owner-only
  # permissions; an existing file is left untouched so its comments and any
  # additional keys survive.
  local file="$1"
  if [ ! -f "$file" ]; then
    mkdir -p "$(dirname "$file")"
    chmod 700 "$(dirname "$file")"
    {
      echo "# $2"
      echo "# Gitignored. Generated by backend/scripts/generate_secrets.sh."
      echo "# Regenerate with: scripts/generate_secrets.sh --force"
    } >"$file"
    chmod 600 "$file"
  fi
}

set_value() {
  # $1 = file, $2 = key, $3 = value. Replaces the key in place and appends it
  # when the key is absent.
  local file="$1" key="$2" value="$3" tmp
  if grep -q "^${key}=" "$file"; then
    tmp="$(mktemp)"
    awk -v key="${key}" -v value="${value}" '
      index($0, key "=") == 1 { print key "=" value; next }
      { print }
    ' "$file" >"$tmp"
    mv "$tmp" "$file"
  else
    printf '%s=%s\n' "$key" "$value" >>"$file"
  fi
}

fingerprint() {
  # First 8 hex characters of the SHA-256 digest: identifies a value in
  # terminal output without disclosing it.
  printf '%s' "$1" | openssl dgst -sha256 -r | cut -c1-8
}

ensure_env_file "${BACKEND_SECRETS}" "Core development secrets (Joblite.Repo, JWT signing)."
JWT_SECRET="$(secret_value "${BACKEND_SECRETS}" JWT_SECRET 64)"
set_value "${BACKEND_SECRETS}" DATABASE_URL "${DATABASE_URL}"
set_value "${BACKEND_SECRETS}" JWT_SECRET "${JWT_SECRET}"

if [ -d "${FRONTEND_DIR}" ]; then
  ensure_env_file "${FRONTEND_SECRETS}" "Web development secrets (JobliteWeb.Endpoint)."
  SECRET_KEY_BASE="$(secret_value "${FRONTEND_SECRETS}" SECRET_KEY_BASE 64)"
  LIVE_SIGNING_SALT="$(secret_value "${FRONTEND_SECRETS}" LIVE_SIGNING_SALT 32)"
  set_value "${FRONTEND_SECRETS}" SECRET_KEY_BASE "${SECRET_KEY_BASE}"
  set_value "${FRONTEND_SECRETS}" LIVE_SIGNING_SALT "${LIVE_SIGNING_SALT}"
else
  echo "note: sibling frontend repository not found at ${FRONTEND_DIR}; web secrets skipped." >&2
fi

echo "wrote ${BACKEND_SECRETS} (0600)"
echo "  DATABASE_URL=ecto://joblite:***@localhost:5543/joblite_dev_db"
JWT_FINGERPRINT="$(fingerprint "${JWT_SECRET}")"
echo "  JWT_SECRET sha256:${JWT_FINGERPRINT}"

if [ -f "${FRONTEND_SECRETS}" ]; then
  echo "wrote ${FRONTEND_SECRETS} (0600)"
  SECRET_FINGERPRINT="$(fingerprint "${SECRET_KEY_BASE}")"
  SALT_FINGERPRINT="$(fingerprint "${LIVE_SIGNING_SALT}")"
  echo "  SECRET_KEY_BASE sha256:${SECRET_FINGERPRINT}"
  echo "  LIVE_SIGNING_SALT sha256:${SALT_FINGERPRINT}"
fi
